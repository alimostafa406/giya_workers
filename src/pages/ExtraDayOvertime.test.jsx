// @vitest-environment jsdom
import React from 'react'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import ExtraDayOvertime from './ExtraDayOvertime'
globalThis.React=React
const m=vi.hoisted(()=>({reviews:vi.fn(),decide:vi.fn()}))
vi.mock('../api/extraDayOvertimeApi',()=>({getExtraDayEndReviews:m.reviews,getExtraDayTeams:async()=>[{id:'painting',name:'Peinture Raghibe'},{id:'other',name:'Any Other Team'}],decideExtraDays:m.decide}))
vi.mock('../utils/attendanceOperationalGate',()=>({kinshasaClock:()=>({date:'2026-11-14'})}))
const row=name=>({rule_id:'internal',worker_id:name,work_date:'2026-11-13',status:'pending',locked:false,review:{version:0},source:{fingerprint:'real',worker:{full_name:name,employee_code:name,team_name:'Peinture Raghibe'},attendance:{status:'present'},events:[{id:'event',employee_no:'025',device:'office-main',timestamp:'2026-11-13T22:48:00Z'}],start:'2026-11-13T06:50:00Z',end:'2026-11-13T22:48:00Z',special_start:'2026-11-13T16:00:00Z',qualifying_threshold:'2026-11-13T22:30:00Z',qualified:true,daily_wage:20000,currency:'CDF',duration_minutes:408}})
beforeEach(()=>{m.reviews.mockResolvedValue([row('A'),row('B')]);m.decide.mockResolvedValue([])})
afterEach(()=>{cleanup();vi.clearAllMocks()})
async function chooseTeam(team='painting'){
 await screen.findByRole('option',{name:'Peinture Raghibe'})
 fireEvent.change(screen.getByLabelText('التاريخ'),{target:{value:'2026-11-13'}})
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:team}})
 expect(m.reviews).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 await screen.findByLabelText('اختيار A')
}
it('date/team loads evidence without rule creation, also supports arbitrary teams',async()=>{
 render(<ExtraDayOvertime />)
 expect(m.reviews).not.toHaveBeenCalled()
 expect(screen.queryByLabelText('بداية العمل الخاص')).toBeNull()
 expect(screen.getByLabelText('نهاية العمل الخاص').value).toBe('00:00:00')
 expect(screen.getByLabelText('سماح النهاية بالدقائق').value).toBe('30')
 expect(screen.queryByText('اسم القاعدة')).toBeNull();expect(screen.queryByText('حفظ القاعدة')).toBeNull()
 await chooseTeam()
 expect(m.reviews).toHaveBeenLastCalledWith('2026-11-13','painting','00:00:00','30')
 expect(screen.getAllByText('23:30:00')).toHaveLength(2)
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:'other'}})
 expect(screen.queryByLabelText('اختيار A')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 await waitFor(()=>expect(m.reviews).toHaveBeenLastCalledWith('2026-11-13','other','00:00:00','30'))
})
it('changing tolerance clears previous results and requires an explicit new search',async()=>{
 render(<ExtraDayOvertime />);await chooseTeam()
 fireEvent.click(screen.getByLabelText('اختيار A'))
 fireEvent.change(screen.getByLabelText('سماح النهاية بالدقائق'),{target:{value:'0'}})
 expect(screen.queryByLabelText('اختيار A')).toBeNull()
 expect(screen.getByRole('button',{name:'موافقة على المختارين'}).disabled).toBe(true)
 expect(m.reviews).toHaveBeenCalledTimes(1)
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 await waitFor(()=>expect(m.reviews).toHaveBeenLastCalledWith('2026-11-13','painting','00:00:00','0'))
 expect(m.decide).not.toHaveBeenCalled()
})
it.each(['approved','rejected'])('bulk %s sends selected workers only, selection itself never pays',async decision=>{
 render(<ExtraDayOvertime />);await chooseTeam()
 fireEvent.click(screen.getByLabelText('اختيار A'))
 expect(m.decide).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:decision==='approved'?'موافقة على المختارين':'رفض المختارين'}))
 await waitFor(()=>expect(m.decide).toHaveBeenCalledWith([row('A')],decision))
 expect(screen.getAllByText(/20,000/)).toHaveLength(4)
})
it('select all visible excludes locked workers and reload displays persisted decision',async()=>{
 m.reviews.mockResolvedValueOnce([row('A'),{...row('B'),locked:true}]).mockResolvedValue([{...row('A'),status:'approved'},{...row('B'),locked:true}])
 render(<ExtraDayOvertime />);await chooseTeam()
 fireEvent.click(screen.getByRole('button',{name:'اختيار الكل الظاهر'}))
 expect(screen.getByLabelText('اختيار A').checked).toBe(true)
 expect(screen.getByLabelText('اختيار B').checked).toBe(false)
 fireEvent.click(screen.getByRole('button',{name:'موافقة على المختارين'}))
 await screen.findByText('موافق عليه')
 expect(m.decide).toHaveBeenCalledWith([row('A')],'approved')
})
it('ignores stale asynchronous responses when date/team changes',async()=>{
 let resolveOld
 m.reviews.mockImplementationOnce(()=>new Promise(resolve=>{resolveOld=resolve})).mockResolvedValue([row('New')])
 render(<ExtraDayOvertime />)
 await screen.findByRole('option',{name:'Peinture Raghibe'})
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:'painting'}})
 fireEvent.change(screen.getByLabelText('نهاية العمل الخاص'),{target:{value:'01:20:00'}})
 fireEvent.change(screen.getByLabelText('سماح النهاية بالدقائق'),{target:{value:'15'}})
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:'other'}})
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 await screen.findByLabelText('اختيار New')
 resolveOld([row('Old')])
 await waitFor(()=>expect(screen.queryByLabelText('اختيار Old')).toBeNull())
})
it.each(['00:31:44','23:45:30'])('accepts exact 24-hour seconds %s without changing the submitted date',async end=>{
 render(<ExtraDayOvertime />)
 await screen.findByRole('option',{name:'Peinture Raghibe'})
 fireEvent.change(screen.getByLabelText('التاريخ'),{target:{value:'2026-11-13'}})
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:'painting'}})
 const input=screen.getByLabelText('نهاية العمل الخاص')
 expect(input.type).toBe('text')
 expect(input.dir).toBe('ltr')
 fireEvent.change(input,{target:{value:end}})
 expect(input.value).toBe(end)
 fireEvent.click(screen.getByRole('button',{name:'عرض العمال المستحقين'}))
 await waitFor(()=>expect(m.reviews).toHaveBeenCalledWith('2026-11-13','painting',end,'30'))
})
it('formats real next-day evidence, threshold and outside-work clocks with seconds and no AM/PM',async()=>{
 const r=row('A')
 r.source.start='2026-11-13T06:56:12Z'
 r.source.end='2026-11-13T23:31:44Z'
 r.source.events=[{id:'real',device:'office-main',employee_no:'025',timestamp:r.source.end}]
 r.source.outside_work=[{participant_id:'ow',shared_start:'17:00',shared_end:'23:59:45'}]
 m.reviews.mockResolvedValue([r])
 const view=render(<ExtraDayOvertime />)
 await chooseTeam()
 expect(screen.getByText('07:56:12')).toBeTruthy()
 expect(screen.getByText('00:31:44')).toBeTruthy()
 expect(screen.getByText('23:30:00')).toBeTruthy()
 expect(view.container.querySelector('time').textContent).toBe('2026-11-14 00:31:44')
 expect(view.container.textContent).toContain('17:00:00 → 23:59:45')
 expect(view.container.textContent).not.toMatch(/\b(?:AM|PM)\b/)
})
it.each(['24:00:00','23:60:00','23:45','12:31 AM'])('does not submit malformed or 12-hour input %s',async value=>{
 render(<ExtraDayOvertime />)
 await screen.findByRole('option',{name:'Peinture Raghibe'})
 fireEvent.change(screen.getByLabelText('الفريق'),{target:{value:'painting'}})
 fireEvent.change(screen.getByLabelText('نهاية العمل الخاص'),{target:{value}})
 expect(screen.getByRole('button',{name:'عرض العمال المستحقين'}).disabled).toBe(true)
 expect(m.reviews).not.toHaveBeenCalled()
})
